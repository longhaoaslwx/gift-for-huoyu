# -*- coding: utf-8 -*-
"""按当月全部文案的语气，判断 UP 主的整体心情，输出 0~1 的「愉悦度」。

为什么要多个信号而不是只数好词：
  她的文案以「今日も配信する！」「ありがとう」为骨架，单看好词几乎每月都高分。
  真正区分月份的是「语气细节」——颜文字的方向、感叹号的密度、抱怨词、
  以及她特有的口头禅（「〜ね」「〜かな」是平和，「！？」是情绪高涨）。

输出 mood ∈ [0,1]：
  0.0 = 明显低落 / 疲惫
  0.5 = 平稳
  1.0 = 明显开心
"""
import re

# ---------------------------------------------------------------- 词表
# 每个词给权重，越强越接近 ±3。
POS = {
    # 喜悦 / 兴奋
    "嬉しい": 3, "うれしい": 3, "楽しい": 3, "たのしい": 3, "最高": 3,
    "やった": 3, "わくわく": 3, "ワクワク": 3, "幸せ": 3, "しあわせ": 3,
    "楽しみ": 2.4, "うれし": 2.6, "喜": 2.2, "ハッピー": 2.6,
    "面白": 2.0, "おもろ": 2.0, "好き": 2.2, "大好き": 2.8,
    # 感谢 / 温暖
    "ありがとう": 2.0, "感謝": 2.0, "嬉しすぎ": 3,
    # 赞美 / 惊喜
    "すごい": 2.0, "凄い": 2.0, "きれい": 1.8, "可愛い": 2.0, "かわいい": 2.0,
    "美味しい": 2.0, "おいしい": 2.0, "美味": 2.0, "神": 1.6,
    # 期待
    "楽しみにして": 2.4, "待ち遠しい": 2.2,
}

NEG = {
    # 低落 / 悲伤
    "悲しい": -3, "かなしい": -3, "寂しい": -2.8, "さびしい": -2.8,
    "つらい": -2.8, "辛い": -2.6, "しんど": -2.6, "きつい": -2.2,
    "泣": -2.2, "涙": -1.8, "残念": -2.2, "ざんねん": -2.2,
    "ごめん": -1.6, "申し訳": -2.4, "ミス": -1.8, "失敗": -2.0,
    # 疲惫 / 身体
    "疲れ": -2.4, "つかれ": -2.4, "眠い": -1.8, "ねむい": -1.8,
    "体調": -2.0, "風邪": -2.0, "熱": -1.4, "頭痛": -2.0,
    "休みたい": -1.8, "休む": -1.4,
    # 焦虑 / 不安
    "不安": -2.6, "心配": -2.0, "怖い": -2.4, "こわい": -2.4,
    "緊張": -1.6, "ドキドキ": -1.0, "焦": -2.0, "間に合わ": -1.8,
    # 烦躁
    "無理": -2.2, "むり": -2.2, "嫌": -2.0, "いやだ": -2.0,
    "最悪": -3, "怒": -2.4, "イライラ": -2.6, "うざ": -2.4,
    "バグ": -1.6, "重い": -1.4, "遅い": -1.4,
}

# 颜文字 / 表情的方向分（正=笑，负=哭丧）
EMO_POS = ["😊", "😆", "😄", "😁", "🥳", "😉", "😎", "😌", "🙌", "✨", "🎉",
           "👍", "❤", "💕", "🌟", "😇", "🤩", "😍", "(笑)", "w", "ｗ"]
EMO_NEG = ["😭", "😢", "😞", "😔", "😩", "😫", "😰", "😨", "😱", "💦", "😠",
           "😡", "☔", "(´；ω；`)", "（；；）", "(;_;)", "orz", "…"]

# 这些词出现在文本里说明只是「提及」某事，不代表当下情绪，
# 去掉以免「悲しい映画を観た」被算成低落。
NEUTRALIZE = re.compile(r"(映画|ドラマ|アニメ|小説|曲|歌|ゲーム|プレイ|配信)の?(悲しい|怖い|辛い)")


def _count_weights(text, table):
    """长词优先匹配并吃掉已匹配片段，避免「大好き」同时算「好き」。"""
    s = text
    total = 0.0
    hit = 0
    for w in sorted(table, key=len, reverse=True):
        c = s.count(w)
        if c:
            total += table[w] * c
            hit += c
            s = s.replace(w, "\u3000")
    return total, hit


def month_mood(texts):
    """texts: 该月所有动态正文。返回 (mood, detail)。"""
    joined = "\n".join(texts)
    if not joined.strip():
        return 0.5, {"note": "无正文"}

    body = NEUTRALIZE.sub(r"\1", joined)

    pos, pos_n = _count_weights(body, POS)
    neg, neg_n = _count_weights(body, NEG)

    # 表情：她常用 😇 表示「有点无奈的自嘲」，在日文语境里偏中性，权重减半
    epos = sum(body.count(e) * (0.5 if e == "😇" else 1.2) for e in EMO_POS)
    eneg = sum(body.count(e) * 1.4 for e in EMO_NEG)

    # 感叹号密度 = 情绪唤起程度。她开心时句尾「！」会明显变多。
    # 但这是「强度」不是「方向」，所以只在已有方向时放大。
    n_bang = body.count("！") + body.count("!")
    n_qa = body.count("！？") + body.count("!?") + body.count("⁉")
    excite = 1.0 + min(0.4, n_bang / max(len(texts), 1) * 0.06) + min(0.2, n_qa * 0.05)

    # 疑问句略偏中性，不做负向
    raw = (pos + epos) - (neg + eneg)
    # 按正文长度归一（每千字），避免长文月份被机械放大
    per_k = raw / max(len(body) / 1000.0, 1.0)
    # 再按「条数」平滑，避免某月只有几条时极端值
    per_post = (pos + epos - neg - eneg) / max(len(texts), 1)

    score = (per_k * 0.55 + per_post * 0.45) * excite

    # 把 score 压到 0~1：tanh 让极端月份平滑收敛，不会出现全 0 或全 1
    import math
    mood = 0.5 + 0.5 * math.tanh(score / 9.0)

    # --- 置信度收缩
    # 她的文案风格在 2025 年后从长文变成几十字的播报，
    # 这些月份「情绪词少」只是文字少，不代表情绪低。
    # 用「有效字数」做可信度，字数不足时向 0.5 回归，
    # 避免把「写得简短」误判成「心情低落」。
    n_chars = len(re.sub(r"\s+", "", body))
    conf = n_chars / (n_chars + 600.0)   # 600 字约等于可信度 0.5
    mood = 0.5 + (mood - 0.5) * conf

    return mood, {
        "pos": round(pos, 1), "neg": round(neg, 1),
        "epos": round(epos, 1), "eneg": round(eneg, 1),
        "bang": n_bang, "score": round(score, 2), "n": len(texts),
        "chars": n_chars, "conf": round(conf, 2),
    }


def rank_months(raw_moods):
    """把各月的绝对 mood 转成 0~1 的展布值。

    绝对分有个问题：她的文案本身偏积极，69 个月都挤在 0.5~0.99，
    花朵和环色几乎看不出差别。
    但如果只取月内分位，又会失真——若整段时间都在低谷，
    分位仍会把其中最不糟的月份判成「很开心」。

    所以用混合：0.72 权重给分位（拉开差距），0.28 给绝对分。
    绝对分要先减去中性 0.5 再放大，否则它的下限 0.5 会把整条曲线顶在中间，
    永远没有月份能落到最凋败的那一档。
    """
    items = sorted(raw_moods.items(), key=lambda kv: kv[1])
    n = len(items)
    out = {}
    for i, (k, v) in enumerate(items):
        pct = i / max(n - 1, 1)          # 0 = 最不开心，1 = 最开心
        abs_rel = max(0.0, min(1.0, (v - 0.5) * 2.2))  # 0.5 → 0，0.95 → 1
        out[k] = round(0.72 * pct + 0.28 * abs_rel, 4)
    return out
